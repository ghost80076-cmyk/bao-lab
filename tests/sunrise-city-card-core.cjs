const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const UI = require('../js/gameplay-ui-core.js');
const Startup = require('../js/story-startup-core.js');
const raw = JSON.parse(fs.readFileSync('data/characters/community/73/sunrise-city-disorder.json','utf8'));
const context = vm.createContext({console,structuredClone,window:{addEventListener(){}},localStorage:{}});
vm.runInContext(fs.readFileSync('js/character.js','utf8')+'\nthis.Engine=CharacterEngine;',context);
const card = context.Engine.normalize(raw);
assert.equal(card.world_modules.length,12);
assert.equal(card.timeline_policy.version,1);
const ui = UI.normalize(card.gameplay_ui);
assert.equal(ui.builder.fields.length,15);
assert.equal(ui.panels.length,8);
assert.equal(ui.panels.find(p=>p.id==='player').sections.find(s=>s.path==='npcs').variant,'codex','NPC cards display public fields and omit private notes');
assert.equal(Startup.normalize(card.story_startup).cases.length,25,'no route truncated');
for (const route of card.story_startup.cases.slice(20)) {
  const state=structuredClone(card.initial_state);
  UI.applyBuilderValues(ui,{route:route.value},state);
  const start=Startup.apply(card.story_startup,state,card.world_modules);
  assert.ok(start);
  assert.equal(state.location,route.location);
  assert.notEqual(state.modules.player.identity,'依路線身份');
  assert.equal(state.modules.player.ability_rank,'無');
  assert.equal(state.modules.player.registration,'不適用');
  assert.equal(state.modules.quests[0].status,'available');
  assert.equal(state.npcs.length,0);
  assert.doesNotMatch(start.opening.posts[0].content,/YB:SUNRISE|創建|接入/);
  assert.doesNotMatch(start.greeting,/你是誰|請選擇身份/);
}
for (const entry of card.story_startup.cases.slice(0,20)) {
  const state=structuredClone(card.initial_state);
  UI.applyBuilderValues(ui,{start:entry.value},state);
  assert.ok(Startup.apply(card.story_startup,state,card.world_modules));
  assert.equal(state.location,entry.location);
}
const custom=structuredClone(card.initial_state);
UI.applyBuilderValues(ui,{identity:{option:'自訂',custom:'海關顧問'},start:{option:'自訂',custom:'北山診所'},ability:'心靈系',ability_rank:'A',age:10},custom);
const customScene=Startup.apply(card.story_startup,custom,card.world_modules);
assert.equal(custom.location,'北山診所');
assert.equal(custom.modules.player.identity,'海關顧問');
assert.equal(custom.modules.player.ability_rank,'A');
assert.equal(custom.modules.player.age,18);
assert.match(customScene.greeting,/北山診所/);
assert.equal(card.initial_state.modules.player.identity,'依路線身份','catalog remains unchanged');
const invalid=structuredClone(card.story_startup);
invalid.cases[0].patches.push({path:'modules.not_declared.value',value:1});
const unchanged=structuredClone(card.initial_state);unchanged.modules.player.start=invalid.cases[0].value;
const before=JSON.stringify(unchanged);
assert.equal(Startup.apply(invalid,unchanged,card.world_modules),null);
assert.equal(JSON.stringify(unchanged),before,'reject whole patch atomically');
assert.equal(Startup.normalize({version:1,selector_path:'modules.__proto__.value',cases:[]}),null);
assert.equal(Startup.apply(null,{},[]),null,'legacy cards unchanged');
assert.equal(card.lore,'','companion data is not injected a second time as inline lore');
const binding=card.initial_state.worldbookLibrary;
assert.equal(binding.enabled.length,26);
assert.equal(Object.values(binding.pinned).flatMap(p=>p.entries).length,79);
assert.match(JSON.stringify(binding),/人口 500 萬/);
assert.doesNotMatch(JSON.stringify(binding),/人口 800 萬|最富裕的 5% 人口/);
const catalog=JSON.parse(fs.readFileSync('data/character-catalog/community/page-0001.json'));
assert.equal(catalog.filter(c=>c.id===card.id).length,1);
assert.deepEqual(raw.import_metadata.preserved_source,JSON.parse(fs.readFileSync(raw.import_metadata.regex_file)));
const inline=fs.readFileSync('js/author-regex-inline.js','utf8');
const targetFunction=inline.slice(inline.indexOf('  function target()'),inline.indexOf('  function mount('));
const node={classList:{contains:k=>k==='message'||k==='assistant'}};
const greetingRecord={role:'assistant',greeting:true,content:'greeting',id:'m1'};
const targetContext={App:{activeCharacter:{story_startup:{version:1},opening:{posts:[{content:'scene'}]}}},Chat:{messages:[greetingRecord]},stream:{children:[node]},document:{getElementById:()=>({classList:{contains:()=>true}})}};
assert.equal(vm.runInNewContext(targetFunction+'\ntarget()',targetContext),null,'author iframe must not hide native opening choices');
targetContext.Chat.messages=[{...greetingRecord,greeting:false}];
assert.ok(vm.runInNewContext(targetFunction+'\ntarget()',targetContext),'subsequent replies still get regex display');
targetContext.Chat.messages=[];
assert.equal(vm.runInNewContext(targetFunction+'\ntarget()',targetContext),null,'standalone native greeting also stays in host');
targetContext.App.activeCharacter={opening:{posts:[{content:'legacy scene'}]}};
assert.ok(vm.runInNewContext(targetFunction+'\ntarget()',targetContext),'legacy authored greeting still works');
console.log('PASS Sunrise: 25 starts, five routes, custom handoff, adult age, native state, lore and atomic startup validation');

vm.runInContext(fs.readFileSync('js/state.js','utf8')+'\nthis.State=GameState;',context);
const first=context.State.create(card,{});
assert.equal(first.worldbookLibrary.enabled.length,26);
assert.notEqual(first.worldbookLibrary,card.initial_state.worldbookLibrary);
first.worldbookLibrary.enabled=[];
assert.equal(card.initial_state.worldbookLibrary.enabled.length,26,'story opt-out does not mutate the card');
const restored=JSON.parse(JSON.stringify(first));
assert.equal(restored.worldbookLibrary.enabled.length,0,'save roundtrip preserves disabled state');
const next=context.State.create(card,{});
assert.equal(next.worldbookLibrary.enabled.length,26,'new story receives an independent snapshot');
assert.equal(context.State.create(context.Engine.normalize({id:'legacy',name:'Old'}),{}).worldbookLibrary,undefined,'no worldbook defaults leak to old cards');
assert.equal(context.Engine.normalizeWorldbookLibrary({version:1,enabled:[],installed:[],pinned:JSON.parse('{"__proto__":{"meta":{"id":"__proto__"}}}')}),null);
assert.equal(context.Engine.normalizeWorldbookLibrary({version:1,enabled:['mismatch'],installed:[],pinned:{mismatch:{meta:{id:'different'}}}}),null);

context.App={activeCharacter:card,characters:[card],config:{api:{key:'private-api-key'}}};
context.Chat={messages:[],summary:''};
context.window.App=context.App;context.window.Chat=context.Chat;context.window.GameState=context.State;
context.window.CharacterEngine=context.Engine;
context.localStorage={getItem(){return null;},setItem(){},removeItem(){}};
vm.runInContext(fs.readFileSync('js/storage.js','utf8').replace(/Storage\.init\(\);\s*$/,'')+'\nthis.Store=Storage;',context);
context.State.create(card,context.App.config);
const payload=context.Store.buildStoryPayload();
assert.equal(payload.state.worldbookLibrary.enabled.length,26);
assert.equal(payload.config.api.key,undefined,'backup never includes API credentials');
const expectedSnapshot=JSON.stringify(payload.state.worldbookLibrary.pinned);
context.App.characters=[{...card,initial_state:{...card.initial_state,worldbookLibrary:{...card.initial_state.worldbookLibrary,pinned:{}}}}];
assert.equal(context.Store.restoreStory(payload),true);
assert.equal(JSON.stringify(context.State.current.worldbookLibrary.pinned),expectedSnapshot,'restore uses saved packs even with a loaded catalog');
context.State.current.worldbookLibrary.enabled=[];
const optedOut=context.Store.buildStoryPayload();
assert.equal(context.Store.restoreStory(optedOut),true);
assert.equal(context.State.current.worldbookLibrary.enabled.length,0);
const legacyPayload=structuredClone(payload);
delete legacyPayload.state.worldbookLibrary;
delete legacyPayload.character.initial_state.worldbookLibrary;
legacyPayload.character.lore='【世界書：舊作配套｜監獄】舊存檔自己的監獄資料【/世界書】';
context.App.characters=[card];
assert.equal(context.Store.restoreStory(legacyPayload),true);
assert.match(context.App.activeCharacter.lore,/舊存檔自己的監獄資料/,'loaded new catalog must not erase old inline lore');
assert.equal(context.App.activeCharacter.initial_state.worldbookLibrary,undefined);
assert.equal(context.State.current.worldbookLibrary,undefined,'restore does not opt old stories into new packs');
