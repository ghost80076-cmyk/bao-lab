const { test, expect } = require('@playwright/test');
test.use({ reducedMotion: 'reduce' });

for (const width of [390, 1280]) {
  test('author status presets save native per-NPC values and roundtrip (' + width + 'px)', async ({page}) => {
    await page.setViewportSize({width,height:844});
    await page.goto('./character-studio.html');
    await page.waitForFunction(() => Boolean(window.BAOStudioStatusTemplates && window.BAOStudioNPCEditor && window.BAOCharacterStudioFlow));
    await page.locator('[data-creation-route="lorebook"]').click();
    const npcs = page.locator('#studio-npc-editor');
    await npcs.locator('summary').click();
    await npcs.locator('[data-npc-add]').click();
    await npcs.locator('[data-npc-field="name"]').fill('林曼');
    await npcs.locator('[data-npc-field="role"]').fill('老師');
    await npcs.locator('[data-npc-save]').click();
    const panel = page.locator('#studio-status-templates');
    await panel.locator('summary').click();
    await panel.locator('[data-preset="affinity"]').click();
    await panel.locator('[data-preset="hp"]').click();
    await expect(panel.locator('[data-preset="affinity"]')).toBeDisabled();
    await expect(panel.locator('.studio-status-field-row')).toHaveCount(2);
    await expect(panel.locator('[data-status-subject]')).toHaveValue('林曼');
    await panel.locator('[data-value-key="affinity"]').fill('73');
    await page.evaluate(() => BAOCharacterStudioFlow.go('finish',true));
    await page.locator('#studio-save-draft').click();
    await expect(page.locator('#studio-status')).toContainText('人物數值仍有未儲存');
    await page.evaluate(() => BAOCharacterStudioFlow.go('world',true));
    await panel.locator('[data-status-save-values]').click();
    await panel.locator('[data-status-add]').click();
    await panel.locator('[data-status-field="key"]').fill('morale');
    await panel.locator('[data-status-field="label"]').fill('士氣');
    await panel.locator('[data-status-field="default"]').fill('20');
    await panel.locator('[data-status-field="description"]').fill('只根據明確事件更新。');
    await panel.locator('[data-status-save-field]').click();
    await expect(panel.locator('.studio-status-field-row')).toHaveCount(3);
    const exported = await page.evaluate(() => BAOCharacterStudio.toExport(BAOCharacterStudio.readCard()));
    const card = exported.gameplay;
    expect(card.character_status.fields.map(f=>f.key)).toEqual(['affinity','hp','morale']);
    expect(card.initial_state.npcs).toHaveLength(1);
    expect(card.initial_state.npcs[0].name).toBe('林曼');
    expect(card.initial_state.character_statuses['林曼'].affinity).toBe(73);
    expect(card.initial_state.character_statuses['林曼'].hp).toBe(100);
    expect(card.character_status.fields.find(f=>f.key==='morale').description).toContain('明確事件');
    await page.evaluate(() => BAOCharacterStudioFlow.go('finish',true));
    await page.locator('#studio-save-draft').click();
    await expect(page.locator('#studio-status')).toContainText('草稿已儲存在');
    await page.reload();
    await page.waitForFunction(() => Boolean(window.BAOStudioStatusTemplates && window.BAOCharacterStudio));
    await page.locator('#studio-drafts .studio-draft-row button').first().click();
    await page.evaluate(() => BAOCharacterStudioFlow.go('world',true));
    const reopened = page.locator('#studio-status-templates');
    await reopened.locator('summary').click();
    await expect(reopened.locator('.studio-status-field-row')).toHaveCount(3);
    await expect(reopened.locator('[data-status-subject]')).toHaveValue('林曼');
    await expect(reopened.locator('[data-value-key="affinity"]')).toHaveValue('73');
    await expect(reopened.locator('[data-value-key="hp"]')).toHaveValue('100');
    expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1);
  });
}
