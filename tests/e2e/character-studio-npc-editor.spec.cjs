const { test, expect } = require('@playwright/test');
for (const width of [390,1280]) {
  test('creator NPC editor keeps the native card roundtrip at ' + width + 'px', async ({page}) => {
    await page.setViewportSize({width,height:844});
    await page.goto('./character-studio.html');
    await page.waitForFunction(() => Boolean(window.BAOStudioNPCEditor && window.BAOCharacterStudioFlow));
    await page.locator('[data-creation-route="lorebook"]').click();
    const panel = page.locator('#studio-npc-editor');
    await panel.locator('summary').click();
    await panel.locator('[data-npc-add]').click();
    await panel.locator('[data-npc-field="name"]').fill('林曼');
    await panel.locator('[data-npc-field="aliases"]').fill('Queen、曼姐');
    await panel.locator('[data-npc-field="role"]').fill('學院老師');
    await panel.locator('[data-npc-field="relationship"]').fill('林曼信任玩家，不預設雙向。');
    await panel.locator('[data-npc-field="goal"]').fill('查清事件');
    await panel.locator('[data-npc-field="secret"]').fill('尚未揭露的作者備註');
    await expect(panel.locator('[data-npc-fields]')).toBeVisible();
    await expect(page.locator('[name="creator_notes"]')).not.toContainText('尚未揭露的作者備註');
    await page.evaluate(() => BAOCharacterStudioFlow.go('finish',true));
    await page.locator('#studio-save-draft').click();
    await expect(page.locator('#studio-status')).toContainText('請先儲存或取消編輯');
    await page.evaluate(() => BAOCharacterStudioFlow.go('world',true));
    await panel.locator('[data-npc-save]').click();
    await expect(panel.locator('[data-npc-list]')).toContainText('林曼');
    const result=await page.evaluate(() => BAOCharacterStudio.toExport(BAOCharacterStudio.readCard()));
    expect(result.gameplay.initial_state.npcs).toHaveLength(1);
    expect(result.gameplay.initial_state.npcs[0].notes).toContain('查清事件');
    expect(result.gameplay.initial_state.npcs[0].relationship).toContain('不預設雙向');
    expect(JSON.stringify(result.gameplay.initial_state.npcs)).not.toContain('尚未揭露的作者備註');
    expect(result.content.creator_notes).toContain('尚未揭露的作者備註');
    await page.evaluate(() => BAOCharacterStudioFlow.go('finish',true));
    await page.locator('#studio-save-draft').click();
    await expect(page.locator('#studio-status')).toContainText('草稿已儲存在');
    await page.reload();
    await page.waitForFunction(() => Boolean(window.BAOStudioNPCEditor && window.BAOCharacterStudio));
    await page.locator('#studio-drafts .studio-draft-row button').first().click();
    await page.evaluate(() => BAOCharacterStudioFlow.go('world',true));
    await panel.locator('summary').click();
    await panel.getByRole('button',{name:'編輯 林曼'}).click();
    await expect(panel.locator('[data-npc-field="goal"]')).toHaveValue('查清事件');
    await expect(panel.locator('[data-npc-field="secret"]')).toHaveValue('尚未揭露的作者備註');
    await panel.locator('[data-npc-field="goal"]').fill('保護弟弟');
    await panel.locator('[data-npc-save]').click();
    const next=await page.evaluate(() => BAOCharacterStudio.toExport(BAOCharacterStudio.readCard()));
    expect(next.gameplay.initial_state.npcs).toHaveLength(1);
    expect(next.gameplay.initial_state.npcs[0].notes).toContain('保護弟弟');
    expect(next.gameplay.initial_state.npcs[0].notes).not.toContain('查清事件');
    expect(next.content.creator_notes).toContain('尚未揭露的作者備註');
  });
}
