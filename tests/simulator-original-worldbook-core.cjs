'use strict';
const assert=require('node:assert/strict');
const core=require('../js/worldbook-library-core.js');
const catalog=require('../data/simulator-original-worldbook-library.json');
const packs=catalog.packs.map(core.normalizePack);
const common=packs.filter(p=>p.meta.world==='general');
const xia=packs.filter(p=>p.meta.world==='xia-yuhan-av-industry');
const commonCore=common.find(p=>p.meta.id==='simulator-original-core');
const enabled=common.filter(p=>!p.meta.selection_group).map(p=>p.meta.id);
assert.equal(common.length,13);
assert.equal(common.reduce((n,p)=>n+p.entries.length,0),189);
assert.equal(xia.length,4);
assert.equal(xia.reduce((n,p)=>n+p.entries.length,0),30);
assert.equal(commonCore.entries.length,5);
const fixed=core.constants(common,enabled);
assert.ok(fixed.text.length>5000);
for(const entry of commonCore.entries)assert.ok(fixed.text.includes(entry.content));
assert.match(fixed.text,/這是楚門的世界/);
assert.match(fixed.text,/離場期間 NPC 不會停止或等待/);
assert.equal(core.constants(common,[]).text,'');
const style=common.find(p=>p.meta.id==='simulator-style-89');
const withStyle=core.constants(common,[...enabled,style.meta.id]);
assert.ok(withStyle.text.includes(style.entries[0].content));
assert.equal(core.select([commonCore,style],[commonCore.meta.id,style.meta.id],{latestUser:'劇情'}).text,'','fixed rules stay out of keyword budget');
const keyword=core.select(common,enabled,{latestUser:'奇幻',world:'sunrise-city'});
assert.match(keyword.text,/奇幻劇本/,'original generic sources work across worlds');
assert.ok(keyword.text.length<=2200);
const scenes=xia.find(p=>p.meta.id==='xia-yuhan-worldbook-scenes');
assert.match(core.select(xia,xia.map(p=>p.meta.id),{latestUser:'去拍電梯系列',world:'xia-yuhan-av-industry'}).text,/場景 008：電梯系列/);
assert.doesNotMatch(core.select(xia,xia.map(p=>p.meta.id),{latestUser:'電梯',world:'sunrise-city'}).text,/場景 008/);
assert.equal(core.select([scenes],[scenes.meta.id],{latestUser:'繼續',recentAssistant:'接下來是電梯場景'}).entries.length,1);
assert.equal(core.select([scenes],[scenes.meta.id],{latestUser:'繼續',recentAssistant:'接下來是電梯場景'}, {recallMode:'scene'}).text,'');
const card=require('../data/characters/community/7c/xia-yuhan-av-industry.json');
assert.deepEqual(Object.values(card.gameplay.initial_state.worldbookLibrary.pinned),catalog.packs.filter(p=>p.meta.world==='xia-yuhan-av-industry'));
assert.deepEqual(card.gameplay.initial_state.worldbookLibrary.enabled,xia.map(p=>p.meta.id));
assert.ok(!card.gameplay.initial_state.worldbookLibrary.enabled.some(id=>id.startsWith('simulator-original')));
assert.match(card.content.author_instructions,/沿用本作的輕量職涯與原生狀態欄/);
const gated=core.normalizePack({...commonCore,entries:[{...commonCore.entries[0],requires:['known']}]});
assert.equal(core.constants([gated],[gated.meta.id]).text,'');
assert.ok(core.constants([gated],[gated.meta.id],{flags:['known']}).text);
const tooMuch=core.normalizePack({...commonCore,entries:[0,1,2].map(i=>({id:'long-'+i,mode:'constant',content:String(i)+'長'.repeat(10000)}))});
assert.throws(()=>core.constants([tooMuch],[tooMuch.meta.id]),/24000/,'oversized rules fail visibly instead of sending an excerpt or huge request');
console.log('PASS original worldbooks: constant rules, opt-in style, keyword budget, world scope, assistant signals and Xia companion snapshots');
