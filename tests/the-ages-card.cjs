'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const read = p => fs.readFileSync(path.join(__dirname, '..', p), 'utf8');
const json = p => JSON.parse(read(p));
const original = json('docs/sources/the-ages/character.original.json');
const card = json('data/characters/general/shikong-zhimen.json');
const rules = json('data/characters/general/shikong-zhimen.regex.json');
const Core = require('../js/author-regex-core.js');
const context = { console }; vm.createContext(context);
vm.runInContext(read('js/character.js') + '\nthis.engine=CharacterEngine;', context);
assert.equal(context.engine.validate(card).ok, true);
assert.equal(card.meta.author_id, 'chicofy');
assert.ok(fs.existsSync(path.join(__dirname, '..', card.meta.avatar)));
const originalEntries = original.gameplay.initial_state.worldbookLibrary.installed[0].entries;
assert.deepEqual(card.gameplay.initial_state.worldbookLibrary.installed[0].entries, originalEntries);
assert.equal(originalEntries.length, 101);
assert.equal(card.content.npc_rules, original.content.npc_rules);
assert.match(card.content.greeting, /\[\[TG_PANEL\]\]/);
const normalized = Core.normalize(rules);
assert.equal(normalized[0].reason, '');
const rendered = Core.render('[[TG_PANEL]]', normalized, true);
assert.equal(rendered.script, true);
const adapted = rendered.html.match(/<script>([\s\S]*?)<\/script>/)[1];
new vm.Script(adapted);
assert.doesNotMatch(adapted, /\beval\(|localStorage\.|textarea\.uni-textarea|\[data-lt=/);
assert.match(adapted, /window\.BAOTheAges\.draft/);
const sourceRules = json('docs/sources/the-ages/authorAsset.original.json');
const source = sourceRules.rules.map(r => r.replace.match(/id="tg-src\d">([\s\S]*?)<\/script>/)[1]).join('');
// The large authored game-data table is preserved byte for byte, not regenerated by AI.
const data = text => text.match(/var DATA=([\s\S]*?);\n/)[1];
assert.equal(data(adapted), data(source));
// Every original function except the five documented I/O adapters is preserved.
const functions = text => new Map([...text.matchAll(/^function (\w+)\([^\n]*/gm)].map(m => [m[1], m[0]]));
const before = functions(source), after = functions(adapted);
for (const [name, text] of before) {
  if (['ta', 'sendBtn', 'inject', 'pageText', 'vSys'].includes(name)) continue;
  assert.equal(after.get(name), text.replaceAll('localStorage.', 'TGStorage.'), 'changed game function: ' + name);
}
const listed = json('data/characters.json').filter(c => c.id === card.meta.id);
assert.equal(listed.length, 1); assert.equal(listed[0].author_id, 'chicofy');
console.log('PASS The Ages: import, 101 unchanged entries, original data/functions, sandbox adapter and author catalog');
