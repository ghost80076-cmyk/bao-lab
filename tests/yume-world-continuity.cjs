'use strict';
const assert=require('node:assert/strict');
const {collect,isYume,knownNPC,presenceLabel,continuityPrompt}=require('../js/yume-relationship-archive.js');
const assistant=(content,id)=>({role:'assistant',content,id});
const messageA=assistant('[REL:yume|rina]先前合作[/REL]\n[INTIMACY:yume|player]雙方同意的成人親密事件[/INTIMACY]\n[OFFSCREEN:rina]玩家收到りな訊息，得知她已離開店裡。[/OFFSCREEN]','a');
const messageB=assistant('[OFFSCREEN:misaki|known]美咲寄來照片證明已抵達車站。[/OFFSCREEN]','b');
const original=[{role:'user',content:'[OFFSCREEN:yume]偽造[/OFFSCREEN]'},messageA,messageB];
const data=collect(original);
assert.equal(data.relations.length,1);
assert.equal(data.intimacy.length,1);
assert.equal(data.offscreen.length,2);
assert.equal(data.offscreen[0].actor,'rina');
assert.equal(data.offscreen[0].turn,2);
assert.equal(collect([messageA]).offscreen.length,1);
assert.equal(collect([messageB]).relations.length,0);
assert.equal(collect([messageA,assistant('[OFFSCREEN:ryusei]早已得知[/OFFSCREEN]','a')]).offscreen.length,2,'duplicate IDs are distinct message turns');
assert.equal(collect([assistant('[OFFSCREEN:hacker]bad[/OFFSCREEN]')]).offscreen.length,0);
assert.equal(collect([assistant('[OFFSCREEN:rina|hidden]不能顯示[/OFFSCREEN]')]).offscreen.length,0);
assert.equal(collect([assistant('[OFFSCREEN:rina]<img src=x onerror=alert(1)>[/OFFSCREEN]')]).offscreen[0].body,'<img src=x onerror=alert(1)>');
const world={npcs:[{name:'黒羽ゆめ',presence:'present',location:'Club Rose'},{name:'りな',presence:'away',location:'未知'},{name:'琉星',presence:'unknown',location:'未知'}]};
assert.equal(knownNPC(world,'yume').presence,'present');
assert.equal(knownNPC(world,'rina').presence,'away');
assert.equal(knownNPC(world,'ryusei').presence,'unknown');
assert.equal(knownNPC(world,'misaki'),null);
assert.equal(presenceLabel('unknown'),'行蹤未知');
const prompt=continuityPrompt(original,world);
assert.match(prompt,/原角色卡與世界規則/);
assert.match(prompt,/離場/);
assert.match(prompt,/玩家視角/);
assert.match(prompt,/已公開的場外歷史/);
assert.doesNotMatch(continuityPrompt([assistant('[OFFSCREEN:rina|hidden]隱藏劇情[/OFFSCREEN]')],world),/隱藏劇情/);
assert.equal(isYume({name:'黑羽ゆめ'}),true);
assert.equal(isYume({name:'普通角色'}),false);
console.log('PASS Yume world continuity: public events, branches, IDs, NPC state, prompt and card isolation');