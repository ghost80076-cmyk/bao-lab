const assert = require('node:assert/strict');
const core = require('../js/story-discussion-core.js');
const worldbook = require('../js/worldbook-library-core.js');
const draft={characters:[{name:'凜',description:'圖書館員，見到陌生人會保持距離。'}],player:'玩家是旅人',world:'城市有日夜之分',summary:'玩家抵達港口'};
assert.throws(()=>core.parseDraft('{"characters":[]}'));
assert.throws(()=>core.normalizeDraft({...draft,characters:[draft.characters[0],draft.characters[0]]}));
assert.throws(()=>core.normalizeDraft({...draft,world:'x'.repeat(5001)}));
assert.deepEqual(core.parseDraft('```json\n'+JSON.stringify(draft)+'\n```'),draft);
const owner={memory:['舊筆記'],storyActors:{hostedCharacters:[{id:'old',name:'舊人物',background:'不可刪除'}]},modules:{economy:{gold:4}}};
const config={persona:{name:'原玩家',extra:'原補充'},api:{key:'SECRET'}};
const before=JSON.stringify([owner,config]);
const none=core.additions(owner,config,draft,['summary'],'import-test');
assert.deepEqual(none.config,config);
assert.deepEqual(none.state.storyActors,owner.storyActors);
assert.equal(none.state.memory.length,2);
const all=core.additions(owner,config,draft,['characters','world','player','summary'],'import-test');
assert.equal(JSON.stringify([owner,config]),before,'pure reviewed application cannot mutate its source');
assert.equal(all.config.persona.name,'原玩家');
assert.equal(all.config.persona.extra,'原補充\n\n玩家是旅人');
assert.equal(all.state.storyActors.hostedCharacters[0].background,'不可刪除');
assert.equal(all.state.storyActors.hostedCharacters[1].role,'additional');
assert.equal(worldbook.normalizePack(all.state.worldbookLibrary.installed[0]).entries[0].content,draft.world);
assert.equal(all.state.modules.economy.gold,4);
assert.throws(()=>core.additions(all.state,all.config,draft,['characters'],'import-two'),/同名/);
assert.throws(()=>core.additions(owner,config,draft,[],'import-test'));
const request=core.discussionMessages({messages:[{role:'system',content:'HIDDEN_AUTHOR'},{role:'user',content:'VISIBLE'}],summary:'SUMMARY',discussion:[{role:'assistant',content:'DISCUSSION_ONLY'}],question:'QUESTION'});
assert.ok(!JSON.stringify(request).includes('HIDDEN_AUTHOR'));
assert.ok(JSON.stringify(request).includes('VISIBLE'));
assert.equal(request.at(-1).content,'QUESTION');
assert.equal(core.history(Array.from({length:40},(_,i)=>({role:'user',content:String(i)}))).length,24);
assert.equal(core.history([{role:'system',content:'NO'}]).length,0);
console.log('story discussion separation, draft schema, selective additions and native worldbook tests passed');
