const assert = require('node:assert/strict');
const C = require('../js/avatar-chat-core.js');
const a = {id:'a',name:'小雨',aliases:['雨'],avatar:'assets/a.png'};
const b = {id:'b',name:'阿明',aliases:[],avatar:''};
const source = '夜色沉了下來。\n小雨：「你回來了。」\n雨：還要出門嗎？\n阿明：不了。\n陌生人：晚安。\n「這句沒有發話者。」';
const parts=C.parse(source,[a,b]);
assert.deepEqual(parts.filter(x=>x.kind==='speech').map(x=>x.person.id),['a','a','b']);
assert.match(parts.at(-1).text,/陌生人/);
assert.equal(C.parse('小雨：你好',[a,{...b,name:'小雨'}])[0].kind,'narration');
assert.equal(C.parse('**小雨**：你好',[a])[0].person.id,'a');
for(const url of ['javascript:alert(1)','data:image/svg+xml;base64,AAAA','http://example.com/a','assets/../x','blob:evil','https://u:p@e.com/a']) assert.equal(C.image(url),'',url);
assert.equal(C.image('data:image/png;base64,AAAA'),'data:image/png;base64,AAAA');
assert.equal(C.image('https://example.com/a.png'),'https://example.com/a.png');
assert.equal(C.image('data:image/png;base64,'+'A'.repeat(70000)),'');
const normalized=C.normalize({mode:'bad',cast:[a,{...a,id:'a'},b]});
assert.equal(normalized.mode,'standard');assert.equal(new Set(normalized.cast.map(x=>x.id)).size,3);
assert.equal(C.normalize({cast:Array(20).fill(a)}).cast.length,12);
const html=C.render('小雨：<img src=x onerror=alert(1)>',[a]);
assert.ok(!html.includes('<img src=x'));assert.match(html,/&lt;img/);
assert.equal(source,'夜色沉了下來。\n小雨：「你回來了。」\n雨：還要出門嗎？\n阿明：不了。\n陌生人：晚安。\n「這句沒有發話者。」');
console.log('avatar chat: identity ambiguity, text preservation, bounded images and escaping passed');
