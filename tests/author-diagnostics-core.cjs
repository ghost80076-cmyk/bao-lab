const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

global.window = global;
global.localStorage = { getItem: () => null, setItem() {}, removeItem() {} };
global.App = { escapeHTML: text => String(text) };
global.document = { querySelector: () => null, getElementById: () => null };
global.setInterval = () => 1;
global.clearInterval = () => {};
const root = path.join(__dirname, '..');
vm.runInThisContext(fs.readFileSync(path.join(root, 'js/character.js'), 'utf8'));
vm.runInThisContext(fs.readFileSync(path.join(root, 'js/character-readiness.js'), 'utf8'));
vm.runInThisContext(fs.readFileSync(path.join(root, 'js/author-diagnostics.js'), 'utf8'));
const tool = BAOAuthorDiagnostics;
const basic = JSON.parse(fs.readFileSync(path.join(root, 'data/characters/character-basic-template.json'), 'utf8'));
const ok = tool.inspect(basic);
assert.equal(ok.importable, true, JSON.stringify(ok.issues));
assert.equal(typeof ok.score, 'number');
assert.match(tool.reportHTML(ok, '測試卡'), /不代表模型演出分數/);
const missing = structuredClone(basic);
missing.content.system_prompt = '';
const report = tool.inspect(missing);
assert.equal(report.importable, false);
assert.ok(report.issues.some(item => item.path === '$.content.system_prompt' && item.severity === 'error' && item.fix));
const malformed = structuredClone(basic);
malformed.gameplay.world_modules = [{ id: 'dup', fields: [{ key: 'trust' }, { key: 'trust' }] }, { id: 'dup', fields: [] }];
assert.ok(tool.inspect(malformed).issues.some(item => item.path === '$.gameplay.world_modules[1].id'));
assert.ok(tool.inspect(malformed).issues.some(item => item.path === '$.gameplay.world_modules[0].fields[1].key'));
const foreign = tool.inspect({ spec: 'chara_card_v2', data: { name: 'other' } });
assert.equal(foreign.importable, false);
assert.ok(foreign.issues[0].fix.includes('尚未支援'));
assert.throws(() => tool.parse('{\n "meta":,\n}'), /JSON 語法錯誤/);
assert.doesNotMatch(tool.reportHTML({ importable: false, score: null, issues: [{ severity: 'error', path: '$.meta.name', problem: '<img src=x onerror=alert(1)>', fix: '修正' }] }, '<script>alert(1)</script>'), /<script>|<img/);
assert.equal(tool.validEndpoint('http://example.com/v1/chat/completions'), null);
assert.equal(tool.validEndpoint('https://user:secret@example.com/v1/chat/completions'), null);
assert.equal(tool.validEndpoint('https://example.com/v1/chat/completions?key=secret'), null);

(async () => {
  let count = 0;
  const probe = await tool.probeRelay('https://relay.example.test/v1/chat/completions', async (url, init) => {
    count++;
    assert.equal(url, 'https://relay.example.test/v1/chat/completions');
    assert.equal(init.method, 'POST');
    assert.equal(init.mode, 'cors');
    assert.equal(init.credentials, 'omit');
    assert.equal(init.headers.Authorization, 'Bearer BAO_LAB_INVALID_PROBE_KEY');
    assert.ok(!JSON.stringify(init).includes('USER_SECRET'));
    return { status: 401 };
  });
  assert.equal(count, 1);
  assert.equal(probe.reachable, true);
  assert.equal(probe.status, 401);
  assert.match(probe.message, /不代表金鑰/);
  const blocked = await tool.probeRelay('https://relay.example.test/v1/chat/completions', async () => { throw new TypeError('Failed to fetch'); });
  assert.equal(blocked.reachable, false);
  assert.match(blocked.message, /可能是 CORS/);
  console.log('Author structure guidance and keyless relay probe core checks passed.');
})().catch(error => { console.error(error); process.exitCode = 1; });
