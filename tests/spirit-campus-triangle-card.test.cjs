'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const card=require('../data/characters/community/98/spirit-campus-triangle.json');
const sidecar=require('../data/characters/community/98/spirit-campus-triangle.regex.json');
const UI=require('../js/gameplay-ui-core.js');
const Regex=require('../js/author-regex-core.js');
const sandbox={console};vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(require.resolve('../js/character.js'),'utf8')+'\nthis.engine=CharacterEngine;',sandbox);
const engine=sandbox.engine;
assert.equal(card.schema_version,'1.5');
assert.equal(card.meta.author_id,'banzhang');
assert.equal(card.meta.rating,'adult');
const cover='assets/community/98/spirit-campus-triangle.webp';
assert.equal(card.meta.avatar,cover);
assert.equal(card.presentation.reading_background,cover);
assert.equal(require('../data/character-catalog/community/page-0001.json').find(x=>x.id===card.meta.id)?.avatar,cover);
assert.equal(fs.existsSync(require('node:path').join(__dirname,'..',cover)),true);
assert.equal(engine.validate(card).ok,true);
const n=engine.normalize(card);
assert.equal(n.world_modules.length,11);
assert.ok(card.content.lore.includes('【世界書：共鳴訓練｜'));
assert.ok(card.content.system_prompt.includes('性知識'));
assert.ok(card.content.system_prompt.includes('外部關係壓力引擎')||card.content.system_prompt.includes('關係壓力引擎'));
assert.ok(card.content.greeting.includes('小柔')&&card.content.greeting.includes('小雪'));
assert.ok(card.gameplay.initial_state.npcs.every(x=>x.age>=18));
const state=structuredClone(card.gameplay.initial_state);
assert.ok(UI.applyBuilderValues(card.gameplay.ui_schema,{focus:'青梅／女友三角戀',pressure:'較少干擾',pace:'中等推進'},state));
assert.equal(state.modules.setup.focus,'青梅／女友三角戀');
assert.equal(state.modules.setup.pressure,'較少干擾');
assert.equal(state.modules.setup.pace,'中等推進');
const paths=[];const walk=v=>{if(!v||typeof v!=='object')return;for(const[k,x]of Object.entries(v)){if(k==='path'||k==='target_path')paths.push(x);else walk(x)}};
walk(card.gameplay.ui_schema);
for(const p of paths)if(typeof p==='string'&&p.startsWith('modules.'))assert.notEqual(UI.getPath(state,p),undefined,p);
assert.equal(sidecar.characterId,card.meta.id);
const rules=Regex.normalize(sidecar);
const opening=Regex.render(card.content.greeting,rules,false);
assert.equal(opening.matched,false);
const rendered=Regex.render('【YB:SPIRIT:NOTICE】\n實習表已公告。\n【/YB:SPIRIT:NOTICE】',rules,false);
assert.equal(rendered.matched,true);
assert.match(rendered.text||rendered.html||JSON.stringify(rendered),/實習表已公告/);
const noMatch=Regex.render('小雪看了看你，沒有說話。',rules,false);
assert.equal(noMatch.matched,false);
assert.ok(card.presentation.opening.choices.length>=3);
console.log('Spirit campus triangle card validated');
