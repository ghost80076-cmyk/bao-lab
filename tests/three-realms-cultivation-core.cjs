'use strict';
const assert = require('node:assert/strict');
const Core = require('../js/three-realms-cultivation-core.js');
const lower = { route: '下界鬥氣', realm: '鬥皇', energy: 30, energy_max: 100, karma: '輕微', merit: '尚未確認' };
const apply = (before, patch, text = patch.evidence) => Core.validatePatch(before, patch, text);
const unchanged = structuredClone(lower);
assert.equal(apply(lower, { energy: 20 }).ok, false, 'changed values need narration evidence');
assert.equal(apply(lower, { energy: 20, evidence: '不存在' }, '實際正文').ok, false);
assert.equal(apply(lower, { energy: 20, evidence: '消耗十點鬥氣' }).value.energy, 20);
assert.equal(apply(lower, { energy: 101, evidence: '力量溢出' }).ok, false);
for (const bad of [-1, Infinity, NaN, '20', null]) {
  assert.equal(apply(lower, { energy: bad, evidence: '測試' }).ok, false, 'invalid numeric patch is atomic');
}
assert.equal(apply(lower, { progress: 101, evidence: '測試' }).ok, false);
assert.equal(apply(lower, { progress: 75, evidence: '修煉进度為75%' }).value.progress, 75);
assert.deepEqual(lower, unchanged, 'validator never mutates caller state');
assert.deepEqual(Core.clean({ realm: '鬥宗', surprise: '劇情', __proto__: { polluted: true } }), { realm: '鬥宗' });
assert.equal({}.polluted, undefined);
assert.equal(apply({}, { route: '下界鬥氣', realm: '鬥者', evidence: '我是鬥者' }).ok, true);
assert.equal(apply({}, { realm: '鬥者', evidence: '我是鬥者' }).ok, false);
assert.equal(apply({}, { route: '中界', realm: '鬥者', evidence: '測試' }).ok, false);
assert.equal(apply(lower, { realm: '鬥宗', breakthrough_result: '準備', evidence: '準備突破' }).ok, false);
assert.equal(apply(lower, { realm: '鬥宗', breakthrough_result: '失敗', evidence: '突破失敗' }).ok, false);
assert.equal(apply(lower, { breakthrough_result: '失敗', condition: '重傷', evidence: '突破失敗，身受重傷' }).ok, true);
assert.equal(apply(lower, { realm: '鬥宗', breakthrough_result: '成功', evidence: '成功突破鬥宗' }).ok, true);
assert.equal(apply(lower, { realm: '鬥王', breakthrough_result: '成功', evidence: '測試' }).ok, false);
assert.equal(apply(lower, { realm: '鬥王', breakthrough_result: '修為倒退', evidence: '修為倒退至鬥王' }).ok, true);
assert.equal(apply(lower, { route: '', evidence: '測試' }).ok, false);
assert.equal(apply(lower, { realm: '', evidence: '測試' }).ok, false);
const ascension = { route: '中界', realm: '化神期', ascension_result: '成功', evidence: '飛升中界，成為化神期' };
assert.equal(apply(lower, ascension).ok, false, '鬥皇 cannot ascend directly');
assert.equal(apply({ ...lower, realm: '鬥宗' }, ascension).ok, true);
assert.equal(apply({ route: '下界靈氣', realm: '元嬰期' }, ascension).ok, true);
assert.equal(apply({ route: '下界靈氣', realm: '結丹期' }, ascension).ok, false);
assert.equal(apply({ ...lower, realm: '鬥宗' }, { ...ascension, realm: '煉虛期' }).ok, false);
assert.equal(apply({ ...lower, realm: '鬥宗' }, { ...ascension, ascension_result: '失敗' }).ok, false);
const upper = { route: '上界', realm: '小神', ascension_result: '成功', evidence: '渡過九重天劫，飛升為小神' };
for (const realm of ['大乘期', '渡劫期']) assert.equal(apply({ route: '中界', realm }, upper).ok, true);
assert.equal(apply({ route: '中界', realm: '化神期' }, upper).ok, false);
assert.equal(apply(lower, { route: '鬼界', realm: '厲鬼', ascension_result: '墮落', evidence: '墮入鬼界成為厲鬼' }).ok, true);
assert.equal(apply({ route: '鬼界', realm: '厲鬼' }, { route: '上界', realm: '小神', ascension_result: '回歸', evidence: '功德淨化後重塑神格回歸天界' }).ok, true);
assert.equal(apply(lower, { route: '上界', realm: '小神', evidence: '測試' }).ok, false);
assert.equal(apply({ ...lower, breakthrough_result: '成功', evidence: '舊成功' }, { realm: '鬥宗', evidence: '修煉中' }).ok, false, 'old success cannot authorize a later promotion');
assert.equal(apply(lower, { karma: '中度', merit: '救助村民獲得少量功德', evidence: '業力中度，救助村民獲得少量功德' }).value.karma, '中度');
console.log('Three Realms cultivation: evidence, bounds, breakthrough, ascension, fall and preservation passed.');
