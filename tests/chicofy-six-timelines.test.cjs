'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const Core=require('../js/author-regex-core.js'),root=path.resolve(__dirname,'..');
const raw=p=>fs.readFileSync(path.join(root,p),'utf8'),json=p=>JSON.parse(raw(p));
const id='jielai-rensheng',author='齊格飛',authorId='chicofy';
const folder='docs/author-migrations/chicofy-six-timelines/';
const card=json('data/characters/general/'+id+'.json');
const cat=json('data/characters.json'),authors=json('data/authors.json').authors;
const attr=json(folder+'attribution.json'),regex=json('data/characters/general/'+id+'.regex.json');
const previousRegex=json(folder+'welcome.regex.json'),assets=json(folder+'assets.json');
const original=raw(folder+'roleWelcome_original.html'),adapted=raw(folder+'roleWelcome_yorubay.html');
const sha=s=>crypto.createHash('sha256').update(s).digest('hex');
assert.equal(authors.find(x=>x.id===authorId)?.name,author);
assert.equal(card.schema_version,'1.5');
assert.equal(card.meta.id,id);
assert.equal(card.meta.name,'🔞借來的人生｜公園外的六條救贖路');
for(const name of ['author','creator'])assert.equal(card.meta[name],author);
for(const name of ['author_id','creator_id'])assert.equal(card.meta[name],authorId);
assert.equal(card.meta.rating,'adult');
assert.equal(card.meta.category,'male');
assert.equal(card.meta.avatar,'https://i.meee.com.tw/BORVsUi.png');
assert.equal(card.content.greeting,original,'must use original author 3D welcome markup');
assert.equal(sha(card.content.system_prompt),'5e1454c1b7124cb44673761507949562b696b2dda52725c549fbc24c665e6e3d','original system_prompt may not be rewritten');
assert.equal(sha(card.content.author_instructions),'333bf9833e08bfbe304c17dd2c643458bbc8532ca5aff7f9ffdf07498978b037','original roleplay example may not be rewritten');
const wb=card.gameplay.initial_state.worldbookLibrary;
assert.equal(wb.installed.length,1);assert.deepEqual(wb.enabled,['jielai-rensheng-wb']);
assert.equal(wb.installed[0].entries.length,13);
assert.equal(wb.installed[0].meta.author,author);
assert.deepEqual(wb.installed[0].entries.map(x=>x.id),Array.from({length:13},(_,i)=>'jl-'+String(i).padStart(2,'0')));
assert.equal(sha(JSON.stringify(wb.installed[0].entries)),'c7e9e4de2cfc622888f7dd686b690beae501372b6b6a63bd47c03cac8ad0c884','all original worldbook entries, keyword triggers and content must survive');
for(const term of ['【選角鎖定】','【共用時鐘與耗時】','【資金】','【救贖判定】','【引薦鏈】'])assert.ok(card.content.system_prompt.includes(term),'missing '+term);
const entry=cat.filter(x=>x.id===id);assert.equal(entry.length,1);
assert.equal(entry[0].file,'data/characters/general/'+id+'.json');
assert.equal(entry[0].author,author);assert.equal(entry[0].author_id,authorId);
assert.equal(entry[0].rating,'adult');assert.equal(entry[0].category,'male');
assert.equal(entry[0].description,card.meta.description);
assert.equal(entry[0].avatar,card.meta.avatar);
assert.deepEqual(entry[0].supported_modes,card.gameplay.supported_modes);
const previous=cat.find(x=>x.id==='shikong-zhimen');
assert.ok(previous && previous.author===author && previous.author_id===authorId);
assert.equal(attr.published_character_id,id);
assert.equal(attr.public_catalog_entry,true);
assert.equal(attr.requires_full_original_card,false);
assert.equal(attr.publication_status,'catalog_registered');
assert.equal(attr.author_id,authorId);
assert.equal(regex.characterId,id);
assert.equal(regex.rules.length,previousRegex.rules.length);
for(const field of ['name','description','pattern','flags'])assert.equal(regex.rules[0][field],previousRegex.rules[0][field],
  'keep author rule identity and original HTML matching contract');
assert.notEqual(regex.rules[0].replacement,previousRegex.rules[0].replacement,
  'current UI adapter must fix static carousel and broken external image references');
const rules=Core.normalize(regex);assert.equal(rules.length,1);assert.equal(rules[0].reason,'');
const render=Core.render(original,rules,true);
assert.equal(render.matched,true);assert.equal(render.script,true);
assert.equal(render.html.trim(),adapted.trim());
const staticOnly=Core.render(original,rules,false);
assert.equal(staticOnly.matched,true);assert.equal(staticOnly.script,false);
assert.ok(staticOnly.blocked>0);
assert.equal(Core.render('這段內容不是開場，應保留正文。',rules,true).matched,false);
